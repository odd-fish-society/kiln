// The embed rule (spec §7.4): a module's `embed = { name, files }` becomes a
// table of the files' bytes. The output is plain string literals, so any C++
// compiler accepts it, and it holds no path or time: equal files, equal text.
#include "rules/registry.h"

#include <algorithm>
#include <cstdio>

#include "core/util.h"

namespace kiln::rules {
namespace builtin {

namespace {

std::vector<std::string> indexed(const TaskDecl& decl, const std::string& key) {
    std::vector<std::string> out;
    for (size_t i = 0;; ++i) {
        char k[64];
        snprintf(k, sizeof(k), "%s.%04zu", key.c_str(), i);
        auto it = decl.params.find(k);
        if (it == decl.params.end())
            break;
        out.push_back(it->second);
    }
    return out;
}

// A C string literal for a table entry's name.
std::string quoted(const std::string& s) {
    std::string out = "\"";
    for (unsigned char c : s) {
        if (c == '"' || c == '\\') {
            out += '\\';
            out += static_cast<char>(c);
        } else if (c < 0x20 || c >= 0x7f) {
            char buf[8];
            snprintf(buf, sizeof(buf), "\\%03o", c);
            out += buf;
        } else {
            out += static_cast<char>(c);
        }
    }
    return out + "\"";
}

TaskResult run_embed(TaskCtx& ctx) {
    TaskResult r;
    const auto& p = ctx.decl->params;
    auto name = p.find("name"), part = p.find("part"), out = p.find("out");
    if (name == p.end() || part == p.end() || out == p.end()) {
        r.error = "embed: missing params";
        return r;
    }
    const bool header = part->second == "header";
    const auto files = indexed(*ctx.decl, "file");
    const auto entries = indexed(*ctx.decl, "entry");
    if (files.size() != entries.size()) {
        r.error = "embed: files and entries differ in number";
        return r;
    }
    // The table is sorted by entry name, whatever order the files came in.
    std::vector<size_t> order(files.size());
    for (size_t i = 0; i < order.size(); ++i)
        order[i] = i;
    std::sort(order.begin(), order.end(), [&](size_t a, size_t b) { return entries[a] < entries[b]; });

    const std::string& n = name->second;
    std::string h = "// Generated by Kiln's embed rule. Do not edit.\n#pragma once\n\n#include <cstddef>\n\n"
                    "#ifndef KILN_EMBEDDED_FILE_DEFINED\n#define KILN_EMBEDDED_FILE_DEFINED\n"
                    "struct KilnEmbeddedFile {\n    const char* name;\n    const unsigned char* data;\n"
                    "    std::size_t size;\n};\n#endif\n\n"
                    "extern const KilnEmbeddedFile " + n + "_files[];\nextern const std::size_t " + n + "_count;\n";
    std::string cpp = "// Generated by Kiln's embed rule. Do not edit.\n#include \"" + n + ".embed.h\"\n\nnamespace {\n";
    std::string table;
    for (size_t k = 0; !header && k < order.size(); ++k) {
        const size_t i = order[k];
        auto bytes = util::read_file(ctx.workspace_root / files[i]);
        if (!bytes.ok()) {
            r.error = "embed: can't read " + files[i] + ": " + bytes.error;
            return r;
        }
        // A string literal: compilers read one far faster, and in far less
        // memory, than an initializer list of numbers. Printable bytes stay
        // as they are and the rest become three-digit octal escapes (which,
        // unlike hex ones, never swallow the digit after them). The literal's
        // own terminating 0 is the one `size` doesn't count, so text can be
        // read as a C string.
        cpp += "const char kData" + std::to_string(k) + "[] =\n    \"";
        size_t col = 0;
        for (unsigned char c : *bytes) {
            if (col >= 96) {
                cpp += "\"\n    \"";
                col = 0;
            }
            if (c >= 0x20 && c < 0x7f && c != '"' && c != '\\' && c != '?') {
                cpp += static_cast<char>(c);
                col += 1;
            } else {
                const char esc[5] = {'\\', static_cast<char>('0' + (c >> 6)), static_cast<char>('0' + ((c >> 3) & 7)),
                                     static_cast<char>('0' + (c & 7)), 0};
                cpp += esc;
                col += 4;
            }
        }
        cpp += "\";\n";
        table += "    {" + quoted(entries[i]) + ", reinterpret_cast<const unsigned char*>(kData" + std::to_string(k) + "), " +
                 std::to_string(bytes->size()) + "},\n";
    }
    cpp += "} // namespace\n\n";
    // A table of no files still has one element, so the array is never empty;
    // the count says how many are real.
    cpp += "extern const KilnEmbeddedFile " + n + "_files[] = {\n" +
           (table.empty() ? std::string("    {nullptr, nullptr, 0},\n") : table) + "};\n";
    cpp += "extern const std::size_t " + n + "_count = " + std::to_string(order.size()) + ";\n";

    auto w = util::write_file(ctx.workspace_root / out->second, header ? h : cpp);
    if (!w.ok()) {
        r.error = "embed: can't write " + out->second + ": " + w.error;
        return r;
    }
    r.outputs.push_back(out->second);
    r.ok = true;
    return r;
}

} // namespace

void register_embed() {
    register_rule("embed", 2, run_embed); // 2: string literals instead of byte lists
}

} // namespace builtin
} // namespace kiln::rules
